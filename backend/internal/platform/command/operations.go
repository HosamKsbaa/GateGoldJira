type OperationContext struct {
	Actor          Actor
	Operation      Operation
	RetryReference string
}

func (operation Operation) IsMutation() bool {
	switch operation {
	case ActivateProjectCore:
		return true
	case UploadAsset, DetachAsset, StartAssetUpload, AppendAssetChunk, FinalizeAssetUpload, CancelAssetUpload:
		return true
	case SaveTransitionPolicy, SaveField, SaveFieldOption, SaveCustomFields, BackfillFieldDefaults, VoteApproval, ResubmitApproval:
		return true
	case MoveBoardCard, SaveBoardLayout, CreateModernBoard, ReorderBoardCard:
		return true
	case PatchModernIssueField, CreateModernIssue, UpdateModernIssue, MoveModernIssue, SaveWorkflow, SaveWorkflowStage, SaveWorkflowTransition, SetTypeWorkflowBinding, MigrateWorkflowIssues, SaveIssueType, SavePriority, SetProjectDefaults, CreatePlanningItem, UpdatePlanningItem, SetIssuePlanning, UpdateNotificationPreferences, ReorderBacklog, ImportIssues, SaveDevelopmentLink, SaveAutomationRule:
		return true
	case OrganizeIssue, SetIssueWatch, SetIssueLink, SaveIssueSearch, ApproveUser, UpdateUser, CreateProject, UpdateProject, ArchiveProject, RestoreProject, SetMembership, RemoveMembership, CreateIssue, UpdateIssue, PatchIssueField, CreateSubtask, MoveIssue, ReorderIssue, CreateLabel, CreateBoard, UpdateBoard, ArchiveBoard, RestoreBoard, AddDependency, RemoveDependency, CreateComment, UpdateComment, UploadPicture, DetachGalleryPicture, UploadAttachment, DetachAttachment, SetNotificationRead, MarkAllNotificationsRead:
		return true
	default:
		return false
	}
}
